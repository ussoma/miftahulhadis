const pick = (a) => a[Math.floor(Math.random() * a.length)];
const shuffle = (a) => { a = [...a]; for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };
/** question with the right answer at a random place; options must be distinct */
function Q(text, right, wrong, explanation = "", ar = "") {
  const opts = shuffle([right, ...[...new Set(wrong.filter((w) => w !== right))].slice(0, 3)]);
  return { text, ar, options: opts, correct: opts.indexOf(right), explanation };
}

