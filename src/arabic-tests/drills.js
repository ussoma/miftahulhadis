export const PER = 30;
export function drillList() {
  return SETS.map(({ id, title, book, rule, gen, pool }) => {
    const p = pool ? pool() : 0;
    return { id, title, book, rule, generated: !!gen || !!pool,
      info: p ? `${p}+ савол · ҳар бор ${PER}-тои нав` : gen ? `Ҳар бор ${PER} саволи нав` : `То ${PER} савол` };
  });
}
export function drill(id, n = 10) {
  const s = SETS.find((x) => x.id === id);
  if (!s) return null;
  const out = []; const seen = new Set();
  for (let tries = 0; out.length < n && tries < n * 30; tries++) {
    const q = s.make();
    const key = q && (q.full || q.answer || q.text);
    if (!q || (!q.kind && q.options.length < 2) || seen.has(key)) continue;
    seen.add(key); out.push(q);
  }
  return { id: s.id, title: s.title, book: s.book, rule: s.rule, questions: out };
}
