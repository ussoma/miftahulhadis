/** Охири калима чӣ ҳаракат дорад? */
const END = { "َ": "Фатҳа", "ُ": "Замма", "ِ": "Касра", "ْ": "Сукун", "ً": "Танвини насб (ـً)", "ٌ": "Танвини рафъ (ـٌ)", "ٍ": "Танвини ҷарр (ـٍ)" };
function lastMark(w) { let x = w.replace(/ًا$/, "ً").replace(/ا$/, ""); const L = letters(w.replace(/ًا$/, "ً")); const m = L[L.length - 1].m.replace("ّ", ""); return m.length === 1 ? m : null; }
const ENDABLE = SAME.filter(([, r]) => !/(ينَ|ونَ|انِ|يْنِ)$/.test(r) && lastMark(r) && !["يَذْهَبِ", "يَفْهَمِ", "يَتَأَخَّرِ"].includes(r));
export function harakatEnd() {
  const it = pick(ENDABLE.length ? ENDABLE : SAME);
  const [s, r, , tj, why] = it;
  const m = lastMark(r); if (!m) return null;
  return Q(`Дар ҷумлаи «${fill(s, stripV(r))}» охири калимаи «${stripV(r)}» чӣ ҳаракат мегирад?`, END[m], Object.values(END), `${fill(s, r)} — ${tj} ${why}`);
}

// ---------- ҲАРАКАТГУЗОРИИ ДАСТӢ (tashkil) ----------
// Савол: { kind: "tashkil", text, sep, units: [{ b, a, e }], answer, explanation }
// b — асоси воҳид (ҳарф ё калима бе ҳаракати охир), a — ҳаракати дуруст (шадда аввал), e — оё хонанда онро мегузорад
const SH = "ّ";
const norm = (m) => (m.includes(SH) ? SH : "") + m.replace(SH, "");
const LONG = "اىوي";
const TW = LEX.filter(([w]) => stripV(w).length >= 2 && !w.includes("ٰ") && !/^ال/.test(stripV(w)));
export function tashkilWord() {
  const [w, m] = pick(TW);
  const L = letters(w);
  const units = L.map((x) => {
    const a = norm(x.m);
    if (!a) return { b: x.c, a: "", e: false };
    return { b: x.c, a, e: true };
  });
  if (units.filter((u) => u.e).length < 2) return null;
  return { kind: "tashkil", text: `Ба ҳарфҳо ҳаракат гузоред: ${stripV(w)} (${m})`, sep: "", units, options: [], correct: -1, answer: w,
    explanation: `Дуруст: ${w} — ${m}.` };
}
const TS = NAHW.filter(([s, r]) => !fill(s, r).includes("ٰ") && !/[()]/.test(s));
export function tashkilSentence() {
  const [s, r, , tj, why] = pick(TS);
  const full = fill(s, r);
  const units = full.split(" ").map((tok) => {
    const L = letters(tok);
    // охирин ҳарфи дорои ҳаракат (аломатҳои охир ба монанди «.» ва «؟» ҷудо мемонанд)
    let k = L.length - 1; let tail = "";
    while (k >= 0 && !/[ء-ي]/.test(L[k].c)) { tail = L[k].c + L[k].m + tail; k--; }
    if (k < 0 || !L[k].m || LONG.includes(L[k].c) && !L[k].m) return { b: tok, a: "", e: false };
    const a = norm(L[k].m.replace("ٰ", ""));
    if (!a || L[k].m.includes("ٰ")) return { b: tok, a: "", e: false };
    const base = join(L.slice(0, k)) + L[k].c;
    return { b: base, a, e: true, t: tail };
  });
  if (units.filter((u) => u.e).length < 2) return null;
  return { kind: "tashkil", text: "Ба охири калимаҳо ҳаракат гузоред (эъроб):", sep: " ", units, options: [], correct: -1, answer: full,
    explanation: `${full} — ${tj} ${why}` };
}

// ---------- КАЛИМАСОЗӢ ВА ҶУМЛАСОЗӢ (build) ----------
// Савол: { kind: "build", text, sep, tiles: [...], answer: [...], full, explanation }
const ABC = "ابتثجحخدذرزسشصضطظعغفقكلمنهوي";
const BW = LEX.filter(([w]) => !w.includes(" ") && !w.includes("ٰ") && stripV(w).length >= 3 && stripV(w).length <= 7);
export function buildWord() {
  const [w, m] = pick(BW);
  const ans = [...stripV(w)];
  let tiles = shuffle(ans); for (let t = 0; t < 6 && tiles.join("") === ans.join(""); t++) tiles = shuffle(ans);
  return { kind: "build", text: `Калимаро созед: «${m}»`, sep: "", tiles, answer: ans, full: w, options: [], correct: -1,
    explanation: `Маъно: ${m}.` };
}
const BS = NAHW.map(([s, r, , tj, why]) => [fill(s, r), tj, why]).filter(([f]) => !/[—()…]/.test(f) && f.split(" ").length >= 2 && f.split(" ").length <= 7);
export function buildSentence() {
  const [f, tj, why] = pick(BS);
  const ans = f.split(" ");
  let tiles = shuffle(ans); for (let t = 0; t < 5 && tiles.join(" ") === f; t++) tiles = shuffle(ans);
  return { kind: "build", text: `Ҷумларо созед: «${tj}»`, sep: " ", tiles, answer: ans, full: f, options: [], correct: -1,
    explanation: `${tj} ${why}` };
}
