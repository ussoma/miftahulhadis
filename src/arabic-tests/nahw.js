// ---------- ҲАРАКАТ: калима бо маъно, ҳаракатгузории дуруст ----------
const VOW = { "َ": "фатҳа", "ُ": "замма", "ِ": "касра", "ْ": "сукун", "ً": "танвини насб", "ٌ": "танвини рафъ", "ٍ": "танвини ҷарр" };
export const VOWEL_NAMES = VOW;

// ---------- генераторҳо ----------
const pick = (a) => a[Math.floor(Math.random() * a.length)];
const shuffle = (a) => { a = [...a]; for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };
const stripV = (s) => s.replace(/[ً-ْٰ]/g, "");
function Q(text, right, wrong, explanation = "") {
  const opts = shuffle([right, ...[...new Set(wrong.filter((w) => w !== right))].slice(0, 3)]);
  return { text, options: opts, correct: opts.indexOf(right), explanation };
}
const tokens = (m) => new Set(m.toLowerCase().split(/[\s,()?!.]+/).filter((t) => t.length > 1));
const overlaps = (a, b) => { const A = tokens(a); for (const t of tokens(b)) if (A.has(t)) return true; return false; };

export function lexArTj() {
  const [w, m] = pick(LEX);
  const wrong = shuffle(LEX.filter(([x, y]) => x !== w && !overlaps(y, m))).slice(0, 3).map((e) => e[1]);
  return Q(`${w} — маънои ин калима чист?`, m, wrong, `${w} — ${m}.`);
}
export function lexTjAr() {
  const [w, m] = pick(LEX);
  const wrong = shuffle(LEX.filter(([x, y]) => x !== w && !overlaps(y, m))).slice(0, 3).map((e) => e[0]);
  return Q(`«${m}» ба арабӣ чӣ мешавад?`, w, wrong, `${m} — ${w}.`);
}

const SHORT = ["َ", "ُ", "ِ"];
const NAMES4 = { "َ": "Фатҳа", "ُ": "Замма", "ِ": "Касра", "ْ": "Сукун" };
const isMark = (c) => /[ً-ْٰ]/.test(c);
/** letters of a word with their marks: [{ch, marks}] */
function letters(w) { const out = []; for (const c of w) { if (isMark(c) && out.length) out[out.length - 1].m += c; else out.push({ c, m: "" }); } return out; }
const join = (L) => L.map((x) => x.c + x.m).join("");
// калимаҳое, ки танҳо исм ё феъл ҳастанд ва ҳаракатҳояшон пурра аст
const VOC = LEX.filter(([w]) => stripV(w).length >= 3 && !/^ال/.test(stripV(w)));
/** Калимаи бе ҳаракат: кадом ҳаракатгузорӣ дуруст аст? */
export function harakatWord() {
  const [w, m] = pick(VOC);
  const L = letters(w);
  const idx = L.map((x, i) => (x.m.length === 1 && SHORT.includes(x.m) && !"اأإآ".includes(x.c) ? i : -1)).filter((i) => i >= 0);
  if (idx.length < 1) return null;
  const wrong = new Set();
  for (let t = 0; t < 40 && wrong.size < 3; t++) {
    const C = L.map((x) => ({ ...x }));
    const i = pick(idx);
    C[i].m = pick(SHORT.filter((v) => v !== L[i].m));
    if (Math.random() < 0.4 && idx.length > 1) { const j = pick(idx.filter((k) => k !== i)); C[j].m = pick(SHORT.filter((v) => v !== L[j].m)); }
    const f = join(C); if (f !== w) wrong.add(f);
  }
  if (wrong.size < 3) return null;
  return Q(`${stripV(w)} (${m}) — кадом ҳаракатгузорӣ дуруст аст?`, w, [...wrong], `Дуруст: ${w} — ${m}.`);
}
/** Ҳарфи муайян чӣ ҳаракат дорад? */
export function harakatLetter() {
  const [w, m] = pick(VOC);
  const L = letters(w);
  const plain = L.map((x) => x.c);
  const idx = L.map((x, i) => (x.m.length === 1 && NAMES4[x.m] && !"اأإآ".includes(x.c) && plain.filter((c) => c === x.c).length === 1 && i < L.length - 1 ? i : -1)).filter((i) => i >= 0);
  if (!idx.length) return null;
  const i = pick(idx);
  const right = NAMES4[L[i].m];
  return Q(`Дар калимаи ${stripV(w)} (${m}) ҳарфи «${L[i].c}» чӣ ҳаракат дорад?`, right, Object.values(NAMES4), `Дуруст: ${w}.`);
}

const fill = (s, w) => s.replace("…", w);
const SAME = NAHW.filter(([, r, wr]) => wr.filter((x) => stripV(x) === stripV(r)).length >= 2);
